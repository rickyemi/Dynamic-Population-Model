def validate_run(result: dict, export_dir=None) -> None:
    """Assert the run is internally consistent and every promised file exists.

    A pipeline that runs is not the same as one that is right. These are the checks that would
    otherwise fail silently: a filter that dropped a whole sub question, a tipping point that does
    not sit between the two probabilities it was interpolated from, a figure written empty because
    it was closed before saving.
    """
    qc, dat, tps = result["qc"], result["dat"], result["tps"]
    n_facets = len(_facet_order(dat))

    # 1. Coverage. Every sub question, gateway, RERR and statistic present exactly once.
    expected_rows = len(set(dat["SubQ"])) * n_facets * 3
    assert len(qc) == expected_rows, f"QC table has {len(qc)} rows, expected {expected_rows}"
    assert not qc.duplicated(subset=["SubQ", "Gateway", "ERR", "Statistic"]).any()

    # 2. Numeric tipping points inside their sweep; out of range labels pinned to the right end.
    for _, row in tps.iterrows():
        if isinstance(row["Result"], str):
            end = row["SweepMax"] if row["Result"].startswith(">") else row["SweepMin"]
            assert np.isclose(row["x_pos"], end), \
                f"{row['Key']} {row['DataType']} pinned to the wrong end"
        else:
            assert row["SweepMin"] <= row["Result"] <= row["SweepMax"], \
                f"{row['Key']} {row['DataType']} tipping point is outside its sweep"

    # 3. The interpolation itself: the mean curve must change sign across the crossing.
    for key, g in dat[dat["DataType"] == "Mean"].groupby("Key"):
        row = tps[(tps["Key"] == key) & (tps["DataType"] == "Mean")].iloc[0]
        if isinstance(row["Result"], str):
            continue
        g = g.sort_values("Probability")
        below = g.loc[g["Probability"] <= row["Result"], "Result"]
        above = g.loc[g["Probability"] >= row["Result"], "Result"]
        assert len(below) and len(above), f"{key} has no points either side of its tipping point"
        assert below.iloc[-1] * above.iloc[0] <= 0, f"{key} does not change sign at its crossing"

    # 4. Every master model diamond joins to exactly one survivor value.
    assert len(result["mm_init"]) == tps["Key"].nunique(), "A sweep is missing its master marker"
    assert result["mm_init"]["MM.survivor"].notna().all()

    # 5. Every promised file exists and is not empty.
    for palette, paths in result["figures"].items():
        assert len(paths) == len(FIGURE_ORDER) * 2, f"{palette}: expected 8 files"
        assert all(p.exists() and p.stat().st_size > 0 for p in paths), f"{palette}: empty figure"
    targets = [result["qc_file"], result["pdf_file"]]
    if export_dir:
        targets.append(Path(export_dir) / "MANIFEST.txt")
    for path in targets:
        assert Path(path).exists() and Path(path).stat().st_size > 0, f"Missing or empty: {path}"

    print(f"All checks passed: {len(qc)} tipping points across {n_facets} panels and "
          f"{len(set(dat['SubQ']))} transitions, "
          f"{sum(len(v) for v in result['figures'].values())} figure files.")


