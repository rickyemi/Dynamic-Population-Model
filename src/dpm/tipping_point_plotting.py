# (intercept, slope per unit probability): additional initiation falls through zero inside its
# range; the other three stay on one side of it.
SELF_TEST_CURVES = {"5a": (3300.0, -32000.0), "6a": (3300.0, 8000.0),
                    "14b": (1050.0, 63000.0), "15a": (3370.0, -940.0)}


def _self_test_row(group, name, sex, err, mean):
    half = 0.09 * abs(mean) + 180.0
    return {"Model Group": group, "Model Name": name, "Mortality Model": sex, "ERR": err,
            "ERR Variability": "Variable",
            "TP Variability": "Smoking initiation and cessation variable",
            "Age Range": "68 - 72", "Node": "DIFF_ALL", "Mean": mean,
            "95% PI": mean - half, "95% PI2": mean + half,
            "Trans. Prob Stand. Dev.": 0.01, "ERR Standard Deviation": 0.01,
            "QALE Mean": "N/A", "LE Mean": "N/A",
            "Creation Date": pd.Timestamp("2026-09-02 09:57:04"),
            "Web Version": "3.0.0", "R Version": "1.8"}


def _write_self_test_workbook(frame: pd.DataFrame, path: Path) -> Path:
    """Write in the DPM export shape: title row, header row, then data.

    The 95% PI upper bound is written with a blank header, exactly as the DPM leaves it.
    """
    header = ["" if c == "95% PI2" else c for c in frame.columns]
    stacked = pd.concat([pd.DataFrame([["Detailed Model Results"] + [None] * (frame.shape[1] - 1)]),
                         pd.DataFrame([header]),
                         pd.DataFrame(frame.values)], ignore_index=True)
    path.parent.mkdir(parents=True, exist_ok=True)
    with pd.ExcelWriter(path) as xl:
        stacked.to_excel(xl, sheet_name=SHEET, index=False, header=False)
    return path


def build_self_test_inputs(folder) -> Path:
    """Write both synthetic exports, named to the Requirement 1 convention."""
    folder = Path(folder)
    group = f"{SELF_TEST_PRODUCT} YO"                 # Requirement 3
    sweeps, masters = [], []

    for subq, (batch, probs) in SELF_TEST_SWEEPS.items():
        intercept, slope = SELF_TEST_CURVES[subq]
        for gw, gf in (("G10", 1.00), ("G25", 0.88)):
            for sex, sf in (("JAGS_Male_2000", 1.00), ("JAGS_Female_2000", 0.85)):
                for err, ef in ((0.05, 1.00), (0.10, 0.79)):
                    for p in probs:
                        name = f"Master Model {gw} {SELF_TEST_PRODUCT}{batch}_{subq}_{p:.2f}"
                        sweeps.append(_self_test_row(
                            group, name, sex, err, (intercept + slope * p) * gf * ef * sf))

    for gw, gf in (("G10", 1.00), ("G25", 0.88)):
        for sex, sf in (("JAGS_Male_2000", 1.00), ("JAGS_Female_2000", 0.85)):
            for err, ef in ((0.05, 1.00), (0.10, 0.79)):
                name = f"Master Model {gw} {SELF_TEST_PRODUCT} YO_TwoAge_5a_6a_14b_15a_B01"
                masters.append(_self_test_row(group, name, sex, err, 3315.0 * gf * ef * sf))

    tag = SELF_TEST_PRODUCT
    _write_self_test_workbook(pd.DataFrame(sweeps),
                              folder / f"DetailedModelResults_{tag}_TippingPoint.xlsx")
    _write_self_test_workbook(pd.DataFrame(masters),
                              folder / f"DetailedModelResults_{tag}_MasterModels.xlsx")
    return folder


