def build_qc_table(tps: pd.DataFrame) -> pd.DataFrame:
    """Flat table of every tipping point, one row per transition, gateway, RERR and statistic."""
    qc = tps.copy()
    qc["Transition"] = qc["SubQ"].map(TRANSITIONS)
